"""LQR design from the MuJoCo model's mass properties -> core/gains.hpp

Planar wheeled inverted pendulum, generalized coords q = [phi (mean absolute wheel angle), theta (pitch)]:
    [ (M+mw) R^2 + Jw     M R l      ] [phi'' ]   [ tau               ]
    [ M R l               M l^2 + Jp ] [theta''] = [ M g l theta - tau ]
tau = sum of both motor torques. State x = [theta, theta', phi-phi_ref, phi'-phi'_ref, integral(phi-phi_ref)].
"""
import pathlib, numpy as np, mujoco
from scipy.linalg import solve_discrete_are, expm

HERE = pathlib.Path(__file__).parent
DT = 0.002          # 500 Hz control loop (CAN round trip to both motors ≈ 0.3 ms at 1 Mbps)
G = 9.81


def plant(model_path=HERE / "robot_c.xml"):
    m = mujoco.MjModel.from_xml_path(str(model_path))
    ch = m.body("chassis").id
    wl = m.body("wheel_left").id
    R = m.geom_size[m.geom("tyre_left").id][0]
    M = m.body_mass[ch]
    l = m.body_ipos[ch][2]
    Jp = m.body_inertia[ch][1]
    mw = 2 * m.body_mass[wl]
    Jw = 2 * (m.body_inertia[wl][1] + m.dof_armature[m.joint("left_hinge").dofadr[0]])
    track = 2 * abs(m.body_pos[wl][1])
    # yaw inertia of the whole robot about z through the axle centre
    Jz = m.body_inertia[ch][2] + 2 * (m.body_inertia[wl][0] + m.body_mass[wl] * (track / 2) ** 2)
    return dict(R=R, M=M, l=l, Jp=Jp, mw=mw, Jw=Jw, track=track, Jz=Jz)


def lqr(p, q_diag, r):
    R, M, l, Jp, mw, Jw = (p[k] for k in ("R", "M", "l", "Jp", "mw", "Jw"))
    Mm = np.array([[(M + mw) * R ** 2 + Jw, M * R * l], [M * R * l, M * l ** 2 + Jp]])
    Mi = np.linalg.inv(Mm)
    # qdd = Mi @ ([0, M g l] * theta + [1, -1] * tau)
    gth = Mi @ np.array([0, M * G * l])
    bt = Mi @ np.array([1.0, -1.0])
    # x = [theta, theta_d, phi, phi_d, int_phi]
    A = np.zeros((5, 5)); B = np.zeros((5, 1))
    A[0, 1] = 1; A[2, 3] = 1; A[4, 2] = 1
    A[1, 0] = gth[1]; A[3, 0] = gth[0]
    B[1, 0] = bt[1]; B[3, 0] = bt[0]
    # zero-order-hold discretisation
    E = expm(np.block([[A, B], [np.zeros((1, 6))]]) * DT)
    Ad, Bd = E[:5, :5], E[:5, 5:]
    # one control period of actuation delay (CAN + drive): the command computed now acts during the NEXT period.
    # Augmented state z = [x, u_prev]:  z+ = [[Ad, Bd], [0, 0]] z + [0; 1] u
    Ad = np.block([[Ad, Bd], [np.zeros((1, 5)), np.zeros((1, 1))]])
    Bd = np.vstack([np.zeros((5, 1)), np.ones((1, 1))])
    q_diag = list(q_diag) + [0.0]
    Q = np.diag(q_diag); Rr = np.array([[r]])
    P = solve_discrete_are(Ad, Bd, Q, Rr)
    K = np.linalg.solve(Rr + Bd.T @ P @ Bd, Bd.T @ P @ Ad)
    eig = np.linalg.eigvals(Ad - Bd @ K)
    wn2 = Mi[1, 1] * M * G * l              # body swinging about the axle with the wheels free (tau = 0)
    return K.ravel(), eig, wn2


def main(th_w=0.04, r_w=1.2, wn_yaw=10.0):
    p = plant()
    # weights: 1/max_acceptable^2
    q = [1 / th_w ** 2, 1 / 0.6 ** 2, 1 / (0.10 / p["R"]) ** 2, 1 / (0.6 / p["R"]) ** 2, 1 / (0.05 / p["R"]) ** 2]
    K, eig, wn2 = lqr(p, q, 1 / r_w ** 2)
    print("plant:", {k: round(v, 5) for k, v in p.items()})
    print("K =", np.round(K, 4), " |eig|max =", np.abs(eig).max().round(5))
    # yaw: Jz psi'' = (F_R - F_L) * track/2 = t_diff * 2 * (track/2) / R  with tl = t/2 - t_diff, tr = t/2 + t_diff
    b_yaw = p["track"] / p["R"] / p["Jz"]
    zeta = 0.9
    kp_yaw = wn_yaw ** 2 / b_yaw; kd_yaw = 2 * zeta * wn_yaw / b_yaw
    print(f"yaw: Jz {p['Jz']*1e6:.0f} kg mm2, kp {kp_yaw:.3f} N·m/rad, kd {kd_yaw:.4f} N·m·s/rad")
    hdr = f"""// Generated by sim/design_lqr.py from the shape-C CAD model. Do not edit by hand: re-run the script.
#pragma once
namespace bot {{
struct Params {{
  static constexpr float DT        = {DT}f;      // design sample time, s
  static constexpr float WHEEL_R   = {p['R']:.5f}f;   // m
  static constexpr float TRACK     = {p['track']:.5f}f;   // m, wheel centre to wheel centre
  // LQR: t_sum = -(K0*pitch + K1*pitch_rate + K2*(phi-phi_ref) + K3*(phi_rate-phi_rate_ref) + K4*int(phi-phi_ref) + K5*t_sum_prev)
  static constexpr float K[6] = {{{', '.join(f'{k:.6f}f' for k in K)}}};
  static constexpr float KP_YAW    = {kp_yaw:.5f}f;   // N·m per rad of heading error (differential torque)
  static constexpr float KD_YAW    = {kd_yaw:.5f}f;   // N·m per rad/s of yaw-rate error
  static constexpr float WN2       = {wn2:.4f}f;     // body pendulum about the axle, wheels free (tau = 0), (rad/s)^2
}};
}}  // namespace bot
"""
    (HERE.parent / "core" / "gains.hpp").write_text(hdr)
    print("wrote core/gains.hpp")


if __name__ == "__main__":
    import sys
    main(*[float(a) for a in sys.argv[1:]])
