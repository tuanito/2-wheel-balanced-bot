"""Export a trained PPO policy to core/standup_policy.hpp (plain C++ arrays, no ML library on the robot).

  python ml/export_policy.py ml/runs/standup/best.zip

The policy is the actor's mean (deterministic): tanh MLP 6 -> 64 -> 64 -> 1, output clamped to [-1, 1].
~4.6 k multiply-adds every 10 ms: well under 0.1 ms on the ESP32-S3. Then rebuild (sim: g++ ... libbot.so, Mac:
ml/setup_mac.sh; robot: pio run) and check with `python ml/evaluate.py --compiled`.
"""
import sys, pathlib
import numpy as np
import torch
from stable_baselines3 import PPO

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "core" / "standup_policy.hpp"


def arr(name, a):
    flat = ", ".join(f"{v:.8g}f" for v in a.reshape(-1))
    return f"inline constexpr float {name}[{a.size}] = {{{flat}}};\n"


def main(path):
    model = PPO.load(path, device="cpu")
    pol = model.policy
    lin = [m for m in pol.mlp_extractor.policy_net if isinstance(m, torch.nn.Linear)] + [pol.action_net]
    acts = [m for m in pol.mlp_extractor.policy_net if not isinstance(m, torch.nn.Linear)]
    assert all(isinstance(m, torch.nn.Tanh) for m in acts), "export expects tanh hidden layers"
    W = [l.weight.detach().numpy().astype(np.float32) for l in lin]
    B = [l.bias.detach().numpy().astype(np.float32) for l in lin]
    sizes = [W[0].shape[1]] + [w.shape[0] for w in W]
    assert sizes[0] == 6 and sizes[-1] == 1, sizes
    src = [f"// Learned stand-up policy. GENERATED by ml/export_policy.py from {pathlib.Path(path).name}: do not edit by hand.\n",
           "#pragma once\n#include <cmath>\n\n",
           "constexpr int STANDUP_NOBS = 6;          // inputs: see Controller::standup_obs()\n",
           "constexpr int STANDUP_HOLD = 5;          // the policy acts every 5 control ticks (10 ms)\n",
           "constexpr float STANDUP_TIMEOUT = 2.0f;  // s from the start of the push\n",
           "constexpr bool STANDUP_POLICY_TRAINED = true;\n\nnamespace standup_nn {\n"]
    for i, (w, b) in enumerate(zip(W, B)):
        src += [arr(f"W{i}", w), arr(f"B{i}", b)]
    src.append("}  // namespace standup_nn\n\n")
    src.append("// returns the push for both motors together as a fraction of 2 x torque_limit, in [-1, 1]\n")
    src.append("inline float standup_policy(const float* o) {\n  using namespace standup_nn;\n")
    src.append(f"  float h0[{sizes[1]}], h1[{sizes[2]}];\n")
    src.append(f"  for (int j = 0; j < {sizes[1]}; ++j) {{ float s = B0[j]; for (int i = 0; i < {sizes[0]}; ++i) s += W0[j * {sizes[0]} + i] * o[i]; h0[j] = std::tanh(s); }}\n")
    src.append(f"  for (int j = 0; j < {sizes[2]}; ++j) {{ float s = B1[j]; for (int i = 0; i < {sizes[1]}; ++i) s += W1[j * {sizes[1]} + i] * h0[i]; h1[j] = std::tanh(s); }}\n")
    src.append(f"  float y = B2[0]; for (int i = 0; i < {sizes[2]}; ++i) y += W2[i] * h1[i];\n")
    src.append("  return y > 1.f ? 1.f : (y < -1.f ? -1.f : y);\n}\n")
    OUT.write_text("".join(src))
    # self-check against PyTorch on random inputs
    x = np.random.default_rng(0).uniform(-2, 2, (100, 6)).astype(np.float32)
    ref = np.clip(model.policy.get_distribution(torch.tensor(x)).distribution.mean.detach().numpy()[:, 0], -1, 1)
    h = np.tanh(x @ W[0].T + B[0]); h = np.tanh(h @ W[1].T + B[1]); y = np.clip((h @ W[2].T + B[2])[:, 0], -1, 1)
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} kB), max |numpy - torch| = {np.abs(y - ref).max():.2e}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(pathlib.Path(__file__).parent / "runs" / "standup" / "best.zip"))
